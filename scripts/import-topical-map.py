"""Convert the topical map CSV (exported from the xlsx) into src/data/topical-map.ts.

Usage:
  python scripts/xlsx-to-csv.py data-source/topical-map.csv   # run inside the unzipped xlsx folder
  python scripts/import-topical-map.py
"""
import csv, json, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
rows = list(csv.reader(open(ROOT / "data-source/topical-map.csv", encoding="utf-8")))
header_idx = next(i for i, r in enumerate(rows) if r and r[0] == "Page Type")
def num(v):
    return int(v) if v.strip().isdigit() else None


TYPE = {"Core": "core", "Sub": "sub", "Calculator": "calculator", "Blog": "blog", "Location": "location", "Basic": "basic"}

out = []
for r in rows[header_idx + 1:]:
    if not r or r[0] not in TYPE:
        continue
    out.append({
        "pageType": TYPE[r[0]],
        "primaryKeyword": r[1],
        "secondaryKeywords": [s.strip() for s in r[2].split(";") if s.strip()],
        "searchVolume": num(r[3]),
        "keywordDifficulty": num(r[4]),
        "searchIntent": r[5],
        "path": r[6],
        "seoTitle": r[7],
        "h1": r[8],
        "metaDescription": r[9],
        "parentSilo": r[10],
        "internalLinkingSuggestions": r[11],
        "contentAngle": r[12],
        "funnelStage": r[13],
        "menuItemName": r[14],
        "menuStructure": r[15],
        "breadcrumbStructure": r[16],
    })

body = json.dumps(out, indent=2, ensure_ascii=False)
(ROOT / "src/data/topical-map.ts").write_text(
    "// AUTO-GENERATED by scripts/import-topical-map.py from data-source/topical-map.csv.\n"
    "// This is the source of truth for slugs, titles, H1s and meta descriptions. Do not edit by hand.\n"
    'import type { TopicalMapRow } from "@/types/content";\n\n'
    f"export const topicalMap: TopicalMapRow[] = {body};\n",
    encoding="utf-8",
)
print(f"Wrote {len(out)} rows")
